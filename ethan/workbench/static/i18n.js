let uiLang = "zh";
function t(text) { return uiLang === "en" ? (UI_WORDS[text] || text) : text; }
function uiFixed(text) { return esc(t(String(text ?? ""))); }

// 原文只留在当前页面的标记里；回中文直接重画，不回写接口内容。
function uiText(value, translate) {
  const text = String(value ?? "");
  if (translate && Object.prototype.hasOwnProperty.call(UI_WORDS, text)) return `<span data-ui-fixed>${esc(t(text))}</span>`;
  return `<span ${translate ? 'data-ui-content' : 'data-ui-protect'}>${esc(text)}</span>`;
}
const uiContentCache = new Map();
const uiPending = new Set();
let uiScheduled = false;
function localizeVisible() {
  if (uiScheduled) return;
  uiScheduled = true;
  queueMicrotask(() => {
    uiScheduled = false;
    if (uiLang !== "en") return;
    document.documentElement.lang = "en";
    const roots = ["#nav", "#page", "#overlay", "#undo", "#pops"].map(x => document.querySelector(x)).filter(Boolean);
    for (const root of roots) {
      // Markdown 的每个可见文本片段单独标记，保留链接、代码和引用结构。
      root.querySelectorAll('.md').forEach(box => {
        const walk = document.createTreeWalker(box, NodeFilter.SHOW_TEXT), nodes = [];
        let node;
        while ((node = walk.nextNode())) {
          if (!node.parentElement.closest('code, pre, blockquote, .mdquote, [data-ui-content], [data-ui-protect]') && /[\u4e00-\u9fff]/.test(node.nodeValue)) nodes.push(node);
        }
        for (const node of nodes) {
          const span = document.createElement('span');
          span.setAttribute('data-ui-content', ''); span.textContent = node.nodeValue; node.replaceWith(span);
        }
      });
      // 原话、人名、代码、输入框中的内容永远不送翻译。
      const protectedNode = el => el.closest('[data-ui-protect], blockquote, .quote, .mdquote, code, pre, textarea, input');
      const walk = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      let node;
      while ((node = walk.nextNode())) {
        if (protectedNode(node.parentElement) || node.parentElement.closest('[data-ui-content]')) continue;
        const raw = node.nodeValue, trimmed = raw.trim();
        if (Object.prototype.hasOwnProperty.call(UI_WORDS, trimmed)) node.nodeValue = raw.replace(trimmed, t(trimmed));
      }
      root.querySelectorAll('[aria-label], [title], [placeholder]').forEach(el => {
        if (protectedNode(el)) return;
        for (const key of ['aria-label', 'title', 'placeholder']) {
          const value = el.getAttribute(key);
          if (value) el.setAttribute(key, t(value));
        }
      });
    }
    const groups = new Map();
    for (const root of roots) root.querySelectorAll('[data-ui-content]').forEach(el => {
      if (el.closest('blockquote, .quote, .mdquote, code, pre')) return;
      const text = el.dataset.uiOriginal || el.textContent;
      el.dataset.uiOriginal = text;
      if (!/[\u4e00-\u9fff]/.test(text) || !el.getClientRects().length) return;
      if (uiContentCache.has(text)) { if (el.textContent !== uiContentCache.get(text)) el.textContent = uiContentCache.get(text); return; }
      if (!uiPending.has(text)) {
        if (!groups.has(text)) groups.set(text, []);
        groups.get(text).push(el);
      }
    });
    const entries = [...groups];
    // 串行分批，切回中文或离开页面后不继续发送旧页面内容。
    (async () => {
      for (let i = 0; i < entries.length && uiLang === 'en'; i += 50) {
        const batch = entries.slice(i, i + 50).filter(([, els]) => els.some(el => el.isConnected));
        if (!batch.length) continue;
        batch.forEach(([text]) => uiPending.add(text));
        try {
          const r = await api('/api/translate', { texts: batch.map(([text]) => text) }, 120000);
          if (r.ok && Array.isArray(r.texts) && r.texts.length === batch.length) batch.forEach(([text, els], j) => {
            if (typeof r.texts[j] !== 'string') return;
            uiContentCache.set(text, r.texts[j]);
            if (uiLang === 'en') document.querySelectorAll('[data-ui-content]').forEach(el => {
              if (el.isConnected && el.dataset.uiOriginal === text && el.textContent !== r.texts[j]) el.textContent = r.texts[j];
            });
          });
        } catch (e) { /* 翻译不可用时保留原文，页面照常操作。 */ }
        finally { batch.forEach(([text]) => uiPending.delete(text)); }
      }
    })();
  });
  document.documentElement.lang = uiLang === 'en' ? 'en' : 'zh';
}
